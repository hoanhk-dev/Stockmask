# -------------------------
# Checklist Aspect Schema (0/1)
# -------------------------
class ChecklistAspect(BaseModel):
    """Binary presence scoring: 1 = mentioned, 0 = not found"""

    aspect: str
    score: Literal[0, 1]
    evidence: str

    @field_serializer("aspect", "score", "evidence", when_used="json")
    def serialize_optional_fields(self, value):
        return value


# -------------------------
# Governance Report Checklist Signature
# -------------------------
class GovernanceReportChecklist(dspy.Signature):
    """
    You are an ESG governance disclosure checker.
    Score each governance topic ONLY by presence:

    - Score = 1 if the topic is explicitly mentioned
    - Score = 0 if missing

    Do NOT judge quality, only whether the report contains the topic.
    """

    governance_report: str = dspy.InputField(
        desc="Extracted Corporate Governance Report text (ガバナンス報告書)"
    )

    governance_structure: ChecklistAspect = dspy.OutputField(
        desc="Governance structure/model mentioned? (ガバナンス体制)"
    )

    governance_policy: ChecklistAspect = dspy.OutputField(
        desc="Governance principles or policy mentioned? (基本方針)"
    )

    board_composition: ChecklistAspect = dspy.OutputField(
        desc="Board composition or outside directors mentioned? (取締役会構成)"
    )

    committees: ChecklistAspect = dspy.OutputField(
        desc="Committees mentioned? (指名委員会, 報酬委員会, 監査委員会)"
    )

    audit_system: ChecklistAspect = dspy.OutputField(
        desc="Audit system mentioned? (監査体制)"
    )

    internal_control: ChecklistAspect = dspy.OutputField(
        desc="Internal control/compliance mentioned? (内部統制)"
    )

    shareholder_relations: ChecklistAspect = dspy.OutputField(
        desc="Shareholder engagement/IR mentioned? (株主との対話)"
    )

    disclosure_policy: ChecklistAspect = dspy.OutputField(
        desc="Disclosure policy mentioned? (情報開示方針)"
    )

    cross_shareholding: ChecklistAspect = dspy.OutputField(
        desc="Cross-shareholding policy mentioned? (政策保有株式)"
    )

    compensation_system: ChecklistAspect = dspy.OutputField(
        desc="Compensation/remuneration mentioned? (役員報酬制度)"
    )

    risk_management: ChecklistAspect = dspy.OutputField(
        desc="Risk management mentioned? (リスク管理)"
    )

    improvement_actions: ChecklistAspect = dspy.OutputField(
        desc="Governance improvement actions mentioned? (改善取り組み)"
    )


# -------------------------
# Checklist Module (Total /12)
# -------------------------
class GovernanceReportChecklistModule(dspy.Module):
    def __init__(self):
        super().__init__()
        self.checker = dspy.ChainOfThought(GovernanceReportChecklist, n=3)

    def forward(self, governance_report: str):
        result = self.checker(governance_report=governance_report)

        aspects = [
            result.governance_structure,
            result.governance_policy,
            result.board_composition,
            result.committees,
            result.audit_system,
            result.internal_control,
            result.shareholder_relations,
            result.disclosure_policy,
            result.cross_shareholding,
            result.compensation_system,
            result.risk_management,
            result.improvement_actions,
        ]

        total_score = sum(a.score for a in aspects)  # max = 12

        return dspy.Prediction(
            governance_report_content_score=total_score,
            max_score=12,
            aspects=[a.model_dump() for a in aspects],
        )


